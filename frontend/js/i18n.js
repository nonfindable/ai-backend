const STORE_KEY = "startai.lang";

function readLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
  } catch (_) { /* storage can be blocked outright */ }
  try {
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    if (LANGS.includes(nav)) return nav;
  } catch (_) { /* no navigator.language */ }
  return "en";
}

export let lang = readLang();

export function setLang(next) {
  if (!LANGS.includes(next)) return lang;
  lang = next;
  try { localStorage.setItem(STORE_KEY, next); } catch (_) { /* best effort */ }
  document.documentElement.lang = next;
  return lang;
}

export function locale() {
  return LOCALES[lang] || "en";
}

// Missing keys fall back to English rather than rendering a raw key.
export function t(key, vars) {
  const dict = STRINGS[lang] || STRINGS.en;
  let v = dict[key];
  if (v == null) v = STRINGS.en[key];
  if (v == null) return key;
  if (typeof v !== "string" || !vars) return v;
  // A placeholder is {name}. The character class avoids any escaping
  // ambiguity in the pattern itself.
  return v.replace(/\{([A-Za-z0-9_]+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
}

// Grouped lookups: freq, status, tstatus, prio, lvl.
export function tg(group, code) {
  const g = (STRINGS[lang] || STRINGS.en)[group] || {};
  if (g[code] != null) return g[code];
  const en = STRINGS.en[group] || {};
  return en[code] != null ? en[code] : String(code || "");
}

// ── Labels for floating dates ──
import { parseDate, weekdayIndex } from "./dates.js";

export function monthName(monthNumber, short) {
  const list = t(short ? "months_short" : "months");
  return list[Math.max(0, Math.min(11, monthNumber - 1))] || "";
}
export function weekdayName(iso, form) {
  const i = weekdayIndex(iso);
  if (i == null) return "";
  const key = form === "min" ? "weekdays_min" : form === "long" ? "weekdays" : "weekdays_short";
  return t(key)[i] || "";
}
// "5 Oct 2026" — assembled from our own tables, so a floating date is never
// handed to Intl.
export function formatDate(iso, opts = {}) {
  const p = parseDate(iso);
  if (!p) return "";
  const mon = monthName(p.m, opts.short !== false);
  const core = `${p.d} ${mon}`;
  return opts.year === false ? core : `${core} ${p.y}`;
}
export function formatDateWithWeekday(iso) {
  if (!parseDate(iso)) return "";
  return `${weekdayName(iso, "short")}, ${formatDate(iso)}`;
}
export function monthTitle(iso) {
  const p = parseDate(iso);
  return p ? `${monthName(p.m, false)} ${p.y}` : "";
}
// plan.days and perDay[].weekday arrive as Mon/Tue/… codes.
export function dayCodeLabel(code) {
  const idx = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]
    .indexOf(String(code || "").trim().slice(0, 3).toLowerCase());
  return idx < 0 ? String(code || "") : (t("weekdays_short")[idx] || String(code));
}
// Durations read as time, so they are spelled out rather than left in minutes.
export function duration(min) {
  const n = Number(min) || 0;
  const h = Math.floor(n / 60);
  const m = n % 60;
  if (!h) return t("dur_m", { m });
  return m ? t("dur_hm", { h, m }) : t("dur_h", { h });
}
